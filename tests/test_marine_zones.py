"""Tests for the marine zone table offered when adding a marine entry.

The table is generated by ``scripts/build_marine_zones.py`` from NWS. These
tests check it offline: its shape, that it still renders exactly as the
generator writes it (so it was not edited by hand), and that every zone in the
recorded Nearshore Marine Forecasts is in it.
"""

import importlib.util
import os
import re
import unittest

from marine_zones import LAKES, MARINE_ZONES
from parsers import _UGC_START_RE, expand_ugc

_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_FIXTURES = os.path.join(_REPO, "tests", "fixtures")
_TABLE = os.path.join(_REPO, "custom_components", "noaa_it_all", "marine_zones.py")
_SCRIPT = os.path.join(_REPO, "scripts", "build_marine_zones.py")


def _generator():
    spec = importlib.util.spec_from_file_location("build_marine_zones", _SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class TestMarineZoneTable(unittest.TestCase):

    def test_zone_ids_are_valid_and_unique(self):
        zones = [row[0] for row in MARINE_ZONES]
        self.assertEqual(len(zones), len(set(zones)))
        for zone in zones:
            self.assertRegex(zone, r"^[A-Z]{2}Z\d{3}$")
            self.assertIn(zone[:2], LAKES)

    def test_rows_have_a_name_an_office_and_a_great_lakes_location(self):
        for zone, name, office, lat, lon in MARINE_ZONES:
            with self.subTest(zone=zone):
                self.assertTrue(name.strip())
                self.assertNotIn("  ", name)
                self.assertRegex(office, r"^[A-Z]{3}$")
                self.assertTrue(40.0 < lat < 50.0, lat)
                self.assertTrue(-93.0 < lon < -74.0, lon)

    def test_sorted_by_lake_west_to_east_then_zone(self):
        order = list(LAKES)
        keys = [(order.index(row[0][:2]), row[0]) for row in MARINE_ZONES]
        self.assertEqual(keys, sorted(keys))

    def test_chicago_zone(self):
        row = next(row for row in MARINE_ZONES if row[0] == "LMZ741")
        self.assertEqual(row[1:3], ("Wilmette Harbor to Northerly Island IL", "LOT"))

    def test_every_zone_in_the_recorded_forecasts_is_in_the_table(self):
        table = {row[0] for row in MARINE_ZONES}
        for office in ("lot", "buf", "cle", "dlh", "dtx", "mqt"):
            with open(os.path.join(_FIXTURES, f"nsh_{office}.txt")) as f:
                text = f.read()
            for line in text.splitlines():
                if _UGC_START_RE.match(line.strip()):
                    for zone in expand_ugc(line):
                        self.assertIn(zone, table, f"{office}: {zone}")

    def test_table_is_exactly_what_the_generator_renders(self):
        with open(_TABLE, encoding="utf-8") as f:
            committed = f.read()
        self.assertEqual(_generator().render(list(MARINE_ZONES)), committed)

    def test_generator_wraps_long_names_within_120_columns(self):
        row = ("LMZ521", "word " * 40 + "end", "GRB", 45.142, -87.385)
        rendered = _generator().render_row(row)
        self.assertTrue(all(len(line) <= 120 for line in rendered.splitlines()))
        self.assertEqual(eval(rendered.strip().rstrip(",")), row)

    def test_generator_centre_of_a_square(self):
        square = {"type": "Polygon", "coordinates": [[[-88, 42], [-87, 42], [-87, 43], [-88, 43], [-88, 42]]]}
        lat, lon = _generator().centre(square)
        self.assertAlmostEqual(lat, 42.5)
        self.assertAlmostEqual(lon, -87.5)

    def test_no_zone_name_repeats_the_id_format(self):
        for zone, name, *_ in MARINE_ZONES:
            self.assertIsNone(re.fullmatch(r"[A-Z]{2}Z\d{3}", name), zone)


if __name__ == "__main__":
    unittest.main()
